local function globalAchievement(id, name, description, variable, value, icon, progress, hidden)
    return {
        type = "global_variable",
        id = id,
        name = name,
        description = description,
        variable = variable,
        value = value,
        operator = function(self, givenValue)
            return type(givenValue) == "number" and givenValue >= self.value
        end,
        enableProgress = progress or false,
        icon = icon,
        bgColor = "purple",
        hidden = hidden or false,
    }
end

